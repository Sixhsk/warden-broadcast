import { WebSocket } from 'ws';
const ws = new WebSocket('ws://127.0.0.1:7317/ws');
let snap=null; const send=(t,p={})=>ws.send(JSON.stringify({t:'cmd',type:t,payload:p}));
ws.on('message',d=>{const m=JSON.parse(d); if(m.t==='snapshot') snap=m;});
const wait=(ms)=>new Promise(r=>setTimeout(r,ms));
const ok=(c,l,e='')=>console.log((c?'PASS ':'FAIL ')+l+(e?' :: '+e:''));
await new Promise(r=>ws.on('open',r)); await wait(300);
send('timer.set',{durationMs:2000}); await wait(150);
send('timer.cmd',{cmd:'start'}); await wait(200);
const t=snap.state.timer;
const left=t.endsAt-Date.now();
ok(left<=2000 && left>1500,'剩余按结束时间戳换算',String(left));
await wait(2600);
ok(snap.state.timer.phase==='finished' && snap.state.timer.remainingMs===0,'到零自动结束',snap.state.timer.phase);
send('timer.set',{durationMs:90000}); await wait(150);
send('event.set',{stage:'季后赛 · 半决赛'}); await wait(150);
send('setup.done',{}); await wait(200);
ok(snap.state.setupDone===true,'初始化完成标记');
console.log('VERSION',snap.version);
ws.close();
