import { WebSocket } from 'ws';
const ws = new WebSocket('ws://127.0.0.1:7317/ws');
let snap = null; const errs = [];
ws.on('message', (d) => { const m = JSON.parse(d); if (m.t === 'snapshot') snap = m; if (m.t === 'error') errs.push(m.message); });
const send = (type, payload = {}) => ws.send(JSON.stringify({ t: 'cmd', type, payload }));
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const ok = (c, l, e = '') => console.log((c ? 'PASS ' : 'FAIL ') + l + (e ? ' :: ' + e : ''));
await new Promise((r) => ws.on('open', r)); await wait(300);
send('obs.config', { url: 'ws://127.0.0.1:4460' });
send('obs.connect', { url: 'ws://127.0.0.1:4460', password: 'testpass' });
await wait(900);
ok(snap.obs.connected, 'OBS 连接+认证成功', String(snap.obs.error || ''));
ok(snap.obs.obsVersion === '32.0.1', '读到 OBS 版本', String(snap.obs.obsVersion));
ok(Array.isArray(snap.obs.scenes) && snap.obs.scenes.length === 4, '读到场景列表', JSON.stringify(snap.obs.scenes));
send('obs.scene', { scene: '解说特写' }); await wait(500);
ok(snap.obs.scene === '解说特写', '切换场景生效', String(snap.obs.scene));
send('obs.stream', { action: 'start' }); await wait(500);
ok(snap.obs.streaming === true, '开始推流状态');
send('obs.stream', { action: 'stop' }); await wait(500);
ok(snap.obs.streaming === false, '停止推流状态');
const before = errs.length;
send('obs.connect', { url: 'ws://127.0.0.1:4460', password: 'wrong' }); await wait(900);
ok(!snap.obs.connected, '错误密码被拒绝', String(snap.obs.error || 'disconnected'));
console.log('--- done');
ws.close();
