const http=require('http'),WS=require('ws');
const get=u=>new Promise((res,rej)=>{http.get(u,r=>{let d='';r.on('data',c=>d+=c);r.on('end',()=>res(d))}).on('error',rej)});
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
(async()=>{
  const ws=new WS('ws://127.0.0.1:7413/ws');
  const waiters={};let id=0;
  ws.on('message',m=>{const x=JSON.parse(m);if(x.t==='ack'&&waiters[x.id]){waiters[x.id](x.data);delete waiters[x.id]}});
  await new Promise(r=>ws.on('open',r));
  const call=(type,payload)=>new Promise(r=>{const i=++id;waiters[i]=r;ws.send(JSON.stringify({t:'cmd',type,payload,id:i}));setTimeout(()=>{if(waiters[i]){waiters[i]({timeout:true});delete waiters[i]}},8000)});
  await call('obs.config',{url:'ws://127.0.0.1:4460',password:'pw'});
  ws.send(JSON.stringify({t:'cmd',type:'obs.connect',payload:{url:'ws://127.0.0.1:4460',password:'pw'}}));
  await sleep(600);
  await sleep(900);const sim=await call('obs.sim',{scene:'比赛画面',mode:'add'});
  await sleep(500);
  const st1=JSON.parse(await get('http://127.0.0.1:4461/state'));
  const names=Object.keys(st1.inputs).filter(n=>n.startsWith('SIM-'));
  const kinds=[...new Set(names.map(n=>st1.inputs[n].kind))];
  const urlOk=names.filter(n=>String(st1.inputs[n].settings.url||'').endsWith('/sim/'+n.slice(4))).length;
  const items=(st1.items['比赛画面']||[]).filter(i=>i.sourceName.startsWith('SIM-'));
  const enabled1=items.filter(i=>i.sceneItemEnabled).map(i=>i.sourceName);
  await call('player.focus',{playerId:'A1'});
  await sleep(400);
  const st2=JSON.parse(await get('http://127.0.0.1:4461/state'));
  const enabled2=(st2.items['比赛画面']||[]).filter(i=>i.sourceName.startsWith('SIM-')&&i.sceneItemEnabled).map(i=>i.sourceName);
  const again=await call('obs.sim',{scene:'比赛画面',mode:'add'});
  const rm=await call('obs.sim',{scene:'比赛画面',mode:'remove'});
  await sleep(300);
  const st3=JSON.parse(await get('http://127.0.0.1:4461/state'));
  const left=Object.keys(st3.inputs).filter(n=>n.startsWith('SIM-')).length;
  console.log('connect sent');
  console.log('sim.add:', JSON.stringify(sim));
  console.log('inputs:', names.length, 'kinds:', kinds.join(','), 'url-match:', urlOk);
  console.log('scene items:', items.length, 'enabled-before:', enabled1.join('|'));
  console.log('enabled-after-focus-B3:', enabled2.join('|'));
  console.log('re-add:', JSON.stringify(again));
  console.log('remove:', JSON.stringify(rm), 'left:', left);
  // 抓一张模拟源页面
  const j=JSON.parse(await new Promise((res,rej)=>{const rq=http.request('http://127.0.0.1:9333/json/new?http%3A%2F%2F127.0.0.1%3A7413%2Fsim%2FA1',{method:'PUT'},r=>{let d='';r.on('data',c=>d+=c);r.on('end',()=>res(d))});rq.on('error',rej);rq.end()}));
  const cdp=new WS(j.webSocketDebuggerUrl,{perMessageDeflate:false});
  let n=0;const q={};
  cdp.on('message',m=>{const x=JSON.parse(m);if(x.id&&q[x.id]){q[x.id](x.result);delete q[x.id]}});
  await new Promise(r=>cdp.on('open',r));
  const send=(method,params={})=>new Promise(r=>{const i=++n;q[i]=r;cdp.send(JSON.stringify({id:i,method,params}))});
  await send('Emulation.setDeviceMetricsOverride',{width:1440,height:810,deviceScaleFactor:1,mobile:false});
  await sleep(1500);
  const shot=await send('Page.captureScreenshot',{format:'png'});
  require('fs').writeFileSync('D:/AI Working/app/sim-feed.png',Buffer.from(shot.data,'base64'));
  console.log('shot saved');
  process.exit(0);
})().catch(e=>{console.log('ERR',e.message);process.exit(1)});
