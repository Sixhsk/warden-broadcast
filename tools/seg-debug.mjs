import WebSocket from 'ws';
const sleep = ms => new Promise(r => setTimeout(r, ms));
const created = await fetch('http://127.0.0.1:9333/json/new?' + encodeURIComponent('http://127.0.0.1:7412/'), { method: 'PUT' }).then(r => r.json());
const ws = new WebSocket(created.webSocketDebuggerUrl);
await new Promise(r => ws.on('open', r));
let id = 0; const pend = new Map();
ws.on('message', b => { const m = JSON.parse(b); if (m.id && pend.has(m.id)) { pend.get(m.id)(m); pend.delete(m.id); } });
const send = (m, p = {}) => new Promise(res => { const i = ++id; pend.set(i, res); ws.send(JSON.stringify({ id: i, method: m, params: p })); });
const ev = async e => { const r = await send('Runtime.evaluate', { expression: e, returnByValue: true, awaitPromise: true }); return r.result?.exceptionDetails ? 'EXC ' + (r.result.exceptionDetails.exception?.description ?? '') : r.result?.result?.value; };
await sleep(2600);
const box = await ev(`(() => { const row = document.querySelectorAll('.frow')[2];
  const btns = [...row.querySelectorAll('md-outlined-segmented-button')];
  const b = btns[1].getBoundingClientRect();
  return { x: Math.round(b.x+b.width/2), y: Math.round(b.y+b.height/2), before: btns.map(x=>x.selected), rect: [Math.round(b.x), Math.round(b.y), Math.round(b.width), Math.round(b.height)] }; })()`);
console.log('before', JSON.stringify(box));
for (const type of ['mouseMoved','mousePressed','mouseReleased']) await send('Input.dispatchMouseEvent', { type, x: box.x, y: box.y, button: 'left', clickCount: 1 });
await sleep(900);
console.log('after', await ev(`(() => { const row = document.querySelectorAll('.frow')[2];
  return JSON.stringify([...row.querySelectorAll('md-outlined-segmented-button')].map(x=>x.selected)); })()`));
const ws2 = new WebSocket('ws://127.0.0.1:7412/ws');
await new Promise(r => ws2.on('open', r));
ws2.send(JSON.stringify({ t: 'cmd', type: 'player.focus', payload: { playerId: 'B1' }, id: 99 }));
await new Promise(r => setTimeout(r, 300));
console.log('server', await new Promise(res => ws2.on('message', b => { const m = JSON.parse(b); if (m.t === 'snapshot') { res(JSON.stringify(m.state.teams.B.players.map(p => p.id + ':' + (p.alive ? 'A' : 'D')))); } })).catch(e => 'err'));
ws.close(); process.exit(0);
